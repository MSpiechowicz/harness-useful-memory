//! The PostgreSQL schema and its version (the `harness_memory_meta` table).
//!
//! The tables live in the connection's current schema (the first `search_path` entry), so a team
//! can give the memory its own database, or its own schema through the URL's
//! `options=-csearch_path=...`. Migrations run in one transaction under an advisory lock, so
//! clients starting together migrate once; a client that finds a newer version changes nothing.

use postgres::{Client, GenericClient};

use super::{backend, column};
use crate::store::StoreError;

/// The schema version this server writes.
pub const SCHEMA_VERSION: i64 = 4;

/// The advisory lock migrations take (database-wide; "harness-memory migrate"). Writes hold it
/// shared, so a migration waits for running writes and later writes see its version.
pub(super) const MIGRATE_LOCK: i64 = 0x6861_726e_6573_7301;

/// The state of a database after [`migrate`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SchemaState {
    /// At [`SCHEMA_VERSION`].
    Current,
    /// Written by a newer server; left untouched.
    Newer,
}

/// The version table. Its one row, `schema_version`, is the version of the tables.
const META: &str = "
CREATE TABLE IF NOT EXISTS harness_memory_meta (
    key TEXT PRIMARY KEY,
    value BIGINT NOT NULL
);
";

/// Version 1: the SQLite schema (version 2) in PostgreSQL terms. Global rows have a NULL
/// `project_id`; the unique indexes use `coalesce(project_id, 0)` so a title or entity name is
/// unique per scope. `search_title` and `search_body` hold the accent-folded words of the title
/// and body (folded by the server, see `search::fold`), which the `search` vector indexes with
/// the weights title A, tags B, body D. `written_by` is the database role of the latest write.
const V1: &str = "
CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT NOT NULL UNIQUE,
    root_path TEXT NOT NULL,
    remote TEXT,
    created_at BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL
);

CREATE TABLE notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    kind TEXT NOT NULL
        CHECK (kind IN ('outcome', 'problem', 'fix', 'optimisation', 'location', 'decision', 'note')),
    title TEXT NOT NULL,
    title_norm TEXT NOT NULL,
    body TEXT NOT NULL,
    tags TEXT NOT NULL DEFAULT '',
    source TEXT,
    writer_root TEXT,
    via_override BOOLEAN NOT NULL DEFAULT FALSE,
    written_by TEXT NOT NULL DEFAULT current_user,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    hits BIGINT NOT NULL DEFAULT 0,
    search_title TEXT NOT NULL,
    search_body TEXT NOT NULL,
    search TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('simple'::regconfig, search_title), 'A')
        || setweight(to_tsvector('simple'::regconfig, translate(tags, '-_', '  ')), 'B')
        || setweight(to_tsvector('simple'::regconfig, search_body), 'D')
    ) STORED
);
CREATE UNIQUE INDEX notes_title ON notes ((coalesce(project_id, 0)), title_norm);
CREATE INDEX notes_recent ON notes (project_id, updated_at DESC);
CREATE INDEX notes_search ON notes USING GIN (search);

CREATE TABLE entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    name_norm TEXT NOT NULL,
    kind TEXT
);
CREATE UNIQUE INDEX entities_name ON entities ((coalesce(project_id, 0)), name_norm);

CREATE TABLE relations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    src BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    rel TEXT NOT NULL,
    dst BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    note_id BIGINT REFERENCES notes(id) ON DELETE SET NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    UNIQUE (src, rel, dst)
);
CREATE INDEX relations_dst ON relations (dst);
CREATE INDEX relations_note ON relations (note_id);

CREATE TABLE note_entities (
    note_id BIGINT NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
    entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    PRIMARY KEY (note_id, entity_id)
);
CREATE INDEX note_entities_entity ON note_entities (entity_id);
";

/// Version 2: scripts. A name is unique per scope (`coalesce(project_id, 0)`, like note titles);
/// the provenance columns are the notes' ones. Trust in a body stays on each machine, so there is
/// no trust table here.
const V2: &str = "
CREATE TABLE scripts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    language TEXT NOT NULL CHECK (language IN ('sh', 'bash', 'python', 'node', 'bun')),
    body TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    timeout_secs BIGINT NOT NULL,
    source TEXT,
    writer_root TEXT,
    via_override BOOLEAN NOT NULL DEFAULT FALSE,
    written_by TEXT NOT NULL DEFAULT current_user,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    run_count BIGINT NOT NULL DEFAULT 0,
    last_run_at BIGINT,
    last_exit_code INTEGER
);
CREATE UNIQUE INDEX scripts_name ON scripts ((coalesce(project_id, 0)), name);
";

/// Version 3: the hooks a team shares (see [`crate::store::hooks`]), unique by id, with the
/// repository key they apply to (`NULL` for global hooks; a key, not a `projects` row, so no
/// local path goes with it), listed per scope by `created_at`. `written_by` is the database role
/// of the latest write. Only adds a table, so the rows of version 2 are untouched.
const V3: &str = "
CREATE TABLE hooks (
    id TEXT PRIMARY KEY,
    repo TEXT,
    body TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    author TEXT NOT NULL,
    written_by TEXT NOT NULL DEFAULT current_user,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX hooks_repo ON hooks (repo, created_at, id);
";

/// Version 4: the routines a team shares (see [`crate::store::routines`]), with the columns and
/// index of `hooks`. Only adds a table, so the rows of version 3 are untouched. `IF NOT EXISTS`,
/// so a database whose version was set back by hand without dropping the table still migrates.
const V4: &str = "
CREATE TABLE IF NOT EXISTS routines (
    id TEXT PRIMARY KEY,
    repo TEXT,
    body TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    author TEXT NOT NULL,
    written_by TEXT NOT NULL DEFAULT current_user,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS routines_repo ON routines (repo, created_at, id);
";

/// Brings the database to [`SCHEMA_VERSION`]; a newer database is reported, not changed. A
/// database already at the version is only read, so roles without `CREATE` can use it.
pub fn migrate(client: &mut Client) -> Result<SchemaState, StoreError> {
    match version(client)? {
        Some(found) if found > SCHEMA_VERSION => return Ok(SchemaState::Newer),
        Some(SCHEMA_VERSION) => return Ok(SchemaState::Current),
        _ => {}
    }

    // Re-read under the lock: another client may have migrated meanwhile.
    let mut tx = client.transaction().map_err(backend)?;
    tx.execute("SELECT pg_advisory_xact_lock($1)", &[&MIGRATE_LOCK])
        .map_err(backend)?;
    tx.batch_execute(META).map_err(backend)?;

    let found = stored_version(&mut tx)?.unwrap_or(0);

    if found > SCHEMA_VERSION {
        return Ok(SchemaState::Newer);
    }

    if found < 1 {
        tx.batch_execute(V1).map_err(backend)?;
    }

    if found < 2 {
        tx.batch_execute(V2).map_err(backend)?;
    }

    if found < 3 {
        tx.batch_execute(V3).map_err(backend)?;
    }

    if found < 4 {
        tx.batch_execute(V4).map_err(backend)?;
    }

    tx.execute(
        "INSERT INTO harness_memory_meta (key, value) VALUES ('schema_version', $1)
         ON CONFLICT (key) DO UPDATE SET value = excluded.value",
        &[&SCHEMA_VERSION],
    )
    .map_err(backend)?;

    tx.commit().map_err(backend)?;
    Ok(SchemaState::Current)
}

/// The stored version; `None` before the first migration.
pub fn version(client: &mut Client) -> Result<Option<i64>, StoreError> {
    let row = client
        .query_one("SELECT to_regclass('harness_memory_meta') IS NOT NULL", &[])
        .map_err(backend)?;

    if !column::<bool>(&row, 0)? {
        return Ok(None);
    }

    stored_version(client)
}

/// The version row of `harness_memory_meta` (which must exist); `None` when it has no row.
pub(super) fn stored_version(client: &mut impl GenericClient) -> Result<Option<i64>, StoreError> {
    let row = client
        .query_opt(
            "SELECT value FROM harness_memory_meta WHERE key = 'schema_version'",
            &[],
        )
        .map_err(backend)?;

    row.map(|row| column(&row, 0)).transpose()
}

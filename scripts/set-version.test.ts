// Runs with `bun test`. Works on temp copies; never touches the real manifests.
import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const repoRoot = resolve(import.meta.dir, "..");
const script = join(repoRoot, "scripts", "set-version.ts");

const TOML = `[package]
name = "harness_memory"
version = "0.1.0"   # keep me
edition = "2024"
keywords = [
  "mcp",
  "memory",
]
rust-version = "1.98"

[dependencies]
serde = { version = "1.0.229" }

[profile.release]
lto = true
`;

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "harness_memory"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "0.1.0"
`;

let dir: string;
beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "set-version-"));
  writeFileSync(join(dir, "Cargo.toml"), TOML);
  writeFileSync(join(dir, "Cargo.lock"), LOCK);
});
afterEach(() => rmSync(dir, { recursive: true, force: true }));

function run(...args: string[]) {
  const result = Bun.spawnSync(["bun", script, ...args, "--root", dir]);
  return { code: result.exitCode, out: result.stdout.toString(), err: result.stderr.toString() };
}
const read = (name: string) => readFileSync(join(dir, name), "utf8");

describe("set-version", () => {
  test("updates only the package version and the crate's lock entry", () => {
    const { code, out } = run("1.2.3");
    expect(code).toBe(0);
    expect(read("Cargo.toml")).toBe(TOML.replace('version = "0.1.0"   # keep me', 'version = "1.2.3"   # keep me'));
    const lock = read("Cargo.lock");
    expect(lock).toBe(LOCK.replace('"harness_memory"\nversion = "0.1.0"', '"harness_memory"\nversion = "1.2.3"'));
    expect(lock).toContain('name = "serde"\nversion = "0.1.0"');
    expect(out).toContain("Cargo.toml [package]: 0.1.0 -> 1.2.3");
    expect(out).toContain("Cargo.lock harness_memory: 0.1.0 -> 1.2.3");
  });

  test("is idempotent", () => {
    run("2.0.0");
    const toml = read("Cargo.toml");
    const lock = read("Cargo.lock");
    const second = run("2.0.0");
    expect(second.code).toBe(0);
    expect(second.out).toContain("unchanged");
    expect(read("Cargo.toml")).toBe(toml);
    expect(read("Cargo.lock")).toBe(lock);
  });

  test("accepts prerelease and build metadata", () => {
    expect(run("1.0.0-rc.1+build.5").code).toBe(0);
    expect(read("Cargo.toml")).toContain('version = "1.0.0-rc.1+build.5"');
  });

  test.each(["v1.2.3", "1.2", "01.2.3", "1.2.3.4", "latest", "", "1.2.3-"])("rejects %p and leaves files untouched", (bad) => {
    const result = run(bad);
    expect(result.code).not.toBe(0);
    expect(read("Cargo.toml")).toBe(TOML);
    expect(read("Cargo.lock")).toBe(LOCK);
  });

  test("never reaches into a later table when [package] has no version", () => {
    const broken = TOML.replace('version = "0.1.0"   # keep me\n', "").replace(
      '[dependencies]\n',
      '[dependencies]\nversion = "0.1.0"\n',
    );
    writeFileSync(join(dir, "Cargo.toml"), broken);
    const result = run("3.0.0");
    expect(result.code).toBe(1);
    expect(result.err).toContain("[package]");
    expect(read("Cargo.toml")).toBe(broken);
    expect(read("Cargo.lock")).toBe(LOCK);
  });

  test("fails without partial writes when the lock entry is missing", () => {
    const broken = LOCK.replace('name = "harness_memory"', 'name = "other"');
    writeFileSync(join(dir, "Cargo.lock"), broken);
    const result = run("3.0.0");
    expect(result.code).toBe(1);
    expect(result.err).toContain("harness_memory");
    expect(read("Cargo.toml")).toBe(TOML);
    expect(read("Cargo.lock")).toBe(broken);
  });

  test("works on copies of the real manifests and only changes version lines", () => {
    cpSync(join(repoRoot, "Cargo.toml"), join(dir, "Cargo.toml"));
    cpSync(join(repoRoot, "Cargo.lock"), join(dir, "Cargo.lock"));
    expect(run("9.8.7").code).toBe(0);
    for (const name of ["Cargo.toml", "Cargo.lock"]) {
      const before = readFileSync(join(repoRoot, name), "utf8").split(/\r?\n/);
      const after = read(name).split(/\r?\n/);
      expect(after.length).toBe(before.length);
      const changed = after.filter((line, index) => line !== before[index]);
      expect(changed).toEqual(['version = "9.8.7"']);
    }
  });

  test("keeps the CRLF line endings of a Windows checkout", () => {
    for (const name of ["Cargo.toml", "Cargo.lock"]) {
      const lf = readFileSync(join(repoRoot, name), "utf8").replace(/\r\n/g, "\n");
      writeFileSync(join(dir, name), lf.replace(/\n/g, "\r\n"));
    }
    expect(run("9.8.7").code).toBe(0);
    for (const name of ["Cargo.toml", "Cargo.lock"]) {
      const text = read(name);
      expect(text).toContain('version = "9.8.7"\r\n');
      expect(text.replace(/\r\n/g, "")).not.toContain("\n");
    }
  });
});
